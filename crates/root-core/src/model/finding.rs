use serde::{Deserialize, Serialize};
use std::path::PathBuf;

use super::{
    capabilities::PlatformCapabilities,
    classification::{ProposedAction, ProtectionTier, SafetyDecision},
    process::ProcessCandidate,
    provenance::{ConfidenceLevel, FindingEvidence},
    resource::ResourceCandidate,
};

/// The entity discovered by a scanner pass.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "target_type", rename_all = "snake_case")]
pub enum FindingTarget {
    Filesystem(ResourceCandidate),
    Process(ProcessCandidate),
}

impl FindingTarget {
    pub fn display_name(&self) -> String {
        match self {
            FindingTarget::Filesystem(res) => res.location.path.display().to_string(),
            FindingTarget::Process(proc) => {
                format!("PID {} ({})", proc.identity.pid, proc.identity.name)
            }
        }
    }
}

/// A structured finding generated by Root's scanners and policy evaluator.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ScanFinding {
    pub target: FindingTarget,
    pub protection_tier: ProtectionTier,
    pub proposed_action: ProposedAction,
    pub evidence_list: Vec<FindingEvidence>,
    pub confidence: ConfidenceLevel,
    pub explanation: String,
    pub safety_decision: SafetyDecision,
}

/// Consolidated metrics for a scan pass.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct ScanSummary {
    pub total_scanned: u64,
    pub protected_count: u64,
    pub confirm_required_count: u64,
    pub transient_count: u64,
    pub recoverable_count: u64,
    pub non_actionable_count: u64,
    pub reclaimable_storage_bytes: u64,
    pub reclaimable_memory_pss_bytes: u64,
}

/// Complete report of a scan pass.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ScanReport {
    pub timestamp_epoch_secs: i64,
    pub root_paths: Vec<PathBuf>,
    pub findings: Vec<ScanFinding>,
    pub summary: ScanSummary,
    pub capabilities: PlatformCapabilities,
}
